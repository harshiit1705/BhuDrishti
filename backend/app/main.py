@app.get("/api/export/geojson")
def export_geojson():
    features = []
    for pid, p in PARCELS.items():
        rec = store.get(pid)
        if rec and rec.verified_geometry is not None:
            geom = rec.verified_geometry
            source = "surveyor_verified"
        else:
            geom = p.polygon
            source = "ai_preliminary"
        features.append({
            "type": "Feature",
            "properties": {
                "parcel_id": pid, "area_m2": round(geom.area, 2),
                "source": source, "owner": p.owner, "ward": p.ward,
            },
            "geometry": mapping(geom),
        })
    return {
        "type": "FeatureCollection",
        "crs": {"type": "name", "properties": {"name": CRS}},
        "features": features,
        "is_demo_data": True,
        "note": "source=ai_preliminary means no surveyor verification has been recorded yet "
                "for that parcel; source=surveyor_verified means a human-certified geometry is used.",
    }


