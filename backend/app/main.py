# 7. SURVEY PRIORITY QUEUE
# ---------------------------------------------------------------------------
def _build_survey_queue():
    # The queue is the single source of truth for ALL priority tiers. Seeded
    # demo parcels use the seeded cadastral spatial context. Ad-hoc uploaded
    # EXT-* records have no georeferencing, so each extraction is evaluated
    # in isolation for geometry validity; it is not treated as a neighboring
    # parcel merely because the prototype CV transform uses a common local
    # coordinate convention.
    # Read extraction records once so the geometry pass and metadata pass use
    # the same snapshot and do not observe different repository states.
    all_extractions = extraction_store.all()
    extraction_parcels = []
    for r in all_extractions:
        vr = store.get(r.extraction_id)
        geom = vr.verified_geometry if vr and vr.verified_geometry is not None else r.geometry
        source = "surveyor_verified" if vr and vr.verified_geometry is not None else "ai_extraction"
        extraction_parcels.append(Parcel(parcel_id=r.extraction_id, polygon=geom, source=source))
    authoritative_seeded = _authoritative_parcels()
    seeded_issues = run_topology_validation(authoritative_seeded)
    extraction_issues = []
    for extraction_parcel in extraction_parcels:
        extraction_issues.extend(run_topology_validation([extraction_parcel]))
    issues = seeded_issues + extraction_issues
    by_parcel = _issues_by_parcel(issues)
    ranked = []
    for p in authoritative_seeded:
        pid = p.parcel_id
        conf = _confidence_for_geometry(pid, p, by_parcel)
        rec = store.get(pid)
        ranked.append({
            **conf.to_dict(),
            "is_extraction": False,
            "is_demo_data": True,
            "ai_confidence_heuristic": None,
            "topology_issue_count": len(by_parcel.get(pid, [])),
            "verification_status": rec.status if rec else "unverified",
            "geometry_source": p.source,
        })
    extraction_lookup = {r.extraction_id: r for r in all_extractions}
    for ep in extraction_parcels:
        conf = _confidence_for_geometry(ep.parcel_id, ep, by_parcel)
        rec = extraction_lookup.get(ep.parcel_id)
        vr = store.get(ep.parcel_id)
        # ai_confidence_heuristic surfaces the CV pipeline's OWN quality signal
        # (extraction_engine.run_cv_inference -> ExtractionRecord.confidence_heuristic)
        # alongside -- and clearly distinct from -- the survey/topology-derived
        # `confidence` field above. They measure different things and must not
        # be conflated in the UI: one is "how clean was the image segmentation",
        # the other is "how much does this boundary conflict with the cadastre".
        ranked.append({
            **conf.to_dict(),
            "is_extraction": True,
            "is_demo_data": False,
            "ai_confidence_heuristic": rec.confidence_heuristic if rec else None,
            "topology_issue_count": len(by_parcel.get(ep.parcel_id, [])),
            "verification_status": vr.status if vr else "unverified",
            "geometry_source": ep.source,
        })
    ranked.sort(key=lambda c: c["risk_score"], reverse=True)
    return {
        "thresholds": PRIORITY_THRESHOLDS,
        "queue": ranked,
        "count": len(ranked),
        "high_count": sum(1 for r in ranked if r["priority"] == "high"),
        "medium_count": sum(1 for r in ranked if r["priority"] == "medium"),
        "low_count": sum(1 for r in ranked if r["priority"] == "low"),
        "contains_seeded_demo_data": bool(PARCELS),
        "contains_ai_extractions": bool(extraction_parcels),
    }


@app.get("/api/survey-queue")
def get_survey_queue(request: Request):
    """Return the queue, logging actionable server diagnostics without leaking internals."""
    diagnostic_id = uuid.uuid4().hex[:12]
    try:
        return _build_survey_queue()
    except HTTPException:
        raise
    except Exception as exc:
        # Do not turn data/repository failures into an empty or seeded-only 200.
        # Full traceback stays in function logs; clients receive only a correlation ID.
        logger.exception(
            "survey_queue_failed diagnostic_id=%s method=%s path=%s exception_type=%s",
            diagnostic_id, request.method, request.url.path, type(exc).__name__
        )
        raise HTTPException(
            status_code=500,
            detail={"message": "Survey queue could not be generated. Check server logs using diagnostic_id.",
                    "diagnostic_id": diagnostic_id},
        ) from exc


