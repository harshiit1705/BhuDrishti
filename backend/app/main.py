@app.post("/api/extraction/demo")
def run_demo_extraction(payload: dict = Body(...)):
    """
    PROTOTYPE AI EXTRACTION -- SIMULATED INFERENCE.

    This endpoint does NOT run a real YOLO/segmentation model and there is no
    GPU inference behind it. It maps a selected demo ORI-imagery case onto one
    of the pre-seeded demo parcels that already lives in the same in-memory
    `PARCELS` store used by every other endpoint, and returns that parcel's
    real geometry, confidence, and topology status -- computed the same way
    as `/api/parcels/{id}` -- so downstream screens (GIS map, topology
    validation, survey priority, field verification) receive a single
    consistent, genuine record instead of a fabricated number.

    A production version would replace the case lookup below with real
    raster inference over uploaded drone/ORI imagery (e.g. YOLOv8-Seg +
    vectorization), writing a *new* parcel into the store rather than
    selecting an existing one.
    """
    demo_case = payload.get("demo_case", "BD-047")
    if demo_case not in PARCELS:
        raise HTTPException(404, f"No demo imagery case configured for '{demo_case}'")
    p = PARCELS[demo_case]
    issues = run_topology_validation(list(PARCELS.values()))
    by_parcel = _issues_by_parcel(issues)
    conf = _confidence_for(demo_case, by_parcel)

    # Detected-feature count is derived from the real polygon vertex count
    # rather than a placeholder, so it moves with the geometry actually used.
    coords = list(p.polygon.exterior.coords) if p.polygon.exterior else []
    detected_feature_count = max(0, len(coords) - 1)

    return {
        "parcel_id": demo_case,
        "geometry": mapping(p.polygon),
        "area_m2": p.area_m2,
        "owner": p.owner,
        "ward": p.ward,
        "detected_feature_count": detected_feature_count,
        "confidence": round(conf.confidence, 1),
        "priority": conf.priority,
        "topology_issue_count": len(by_parcel.get(demo_case, [])),
        "is_demo_data": True,
        "extraction_mode": "PROTOTYPE_SIMULATED",
        "note": "Simulated AI extraction: no YOLO/segmentation model runs in this "
                "prototype. This maps the selected demo imagery case to a "
                "pre-seeded parcel evaluated by the same geometry/confidence "
                "engine used across the rest of the pipeline.",
    }


