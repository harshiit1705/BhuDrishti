@app.get("/api/parcels")
def list_parcels():
    issues = run_topology_validation(list(PARCELS.values()))
    by_parcel = _issues_by_parcel(issues)
    out = []
    for pid, p in PARCELS.items():
        conf = _confidence_for(pid, by_parcel)
        rec = store.get(pid)
        out.append({
            "parcel_id": pid,
            "area_m2": p.area_m2,
            "owner": p.owner,
            "ward": p.ward,
            "valid_geometry": p.is_valid,
            "confidence": round(conf.confidence, 1),
            "priority": conf.priority,
            "verification_status": rec.status if rec else "unverified",
            "is_demo_data": True,
        })
    return {"parcels": out, "count": len(out)}


@app.get("/api/parcels/{parcel_id}")
def get_parcel(parcel_id: str):
    if parcel_id not in PARCELS:
        raise HTTPException(404, "Parcel not found")
    p = PARCELS[parcel_id]
    issues = run_topology_validation(list(PARCELS.values()))
    by_parcel = _issues_by_parcel(issues)
    conf = _confidence_for(parcel_id, by_parcel)
    elev = _elevation_for(parcel_id) if parcel_id in ELEVATION_DEMO_CONFIG else None
    rec = store.get(parcel_id)
    return {
        "parcel_id": parcel_id,
        "geometry": mapping(p.polygon),
        "area_m2": p.area_m2,
        "owner": p.owner,
        "ward": p.ward,
        "land_use": p.land_use,
        "valid_geometry": p.is_valid,
        "validity_reason": None if p.is_valid else p.validity_reason,
        "confidence": conf.to_dict(),
        "topology_issues": [i.to_dict() for i in by_parcel.get(parcel_id, [])],
        "elevation": elev.__dict__ if elev else None,
        "verification": rec.to_dict() if rec else None,
        "is_demo_data": True,
    }


