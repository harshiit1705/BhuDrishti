def _candidate_topology_issues(record: ExtractionRecord) -> list[dict]:
    """Analyze every image-derived parcel candidate in pixel space.

    These checks are deliberately scoped to one uploaded image. They are not
    cadastral topology against neighbouring legal parcels because the uploaded
    image has no verified georeferencing in this prototype.
    """
    candidates = record.parcel_candidates or []
    polygons = {}
    issues: list[dict] = []
    for candidate in candidates:
        cid = str(candidate.get("candidate_id") or "")
        pts = candidate.get("pixel_polygon") or []
        try:
            poly = Polygon([(float(x), float(y)) for x, y in pts])
        except Exception:
            poly = None
        if poly is None or poly.is_empty:
            continue
        polygons[cid] = poly
        if not poly.is_valid:
            issues.append({
                "candidate_id": cid,
                "issue_type": "self_intersection",
                "severity": "high",
                "area_px": 0.0,
                "related_candidate_ids": [],
                "description": "Candidate polygon is invalid in image pixel space.",
                "recommended_action": "Surveyor review before accepting the boundary."
            })
    ids = list(polygons)
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            pa, pb = polygons[a], polygons[b]
            if pa.intersects(pb):
                inter = pa.intersection(pb)
                if not inter.is_empty and inter.area > 0.5:
                    issues.append({
                        "candidate_id": a,
                        "issue_type": "candidate_overlap",
                        "severity": "medium",
                        "area_px": round(float(inter.area), 2),
                        "related_candidate_ids": [b],
                        "description": f"AI candidate {a} overlaps candidate {b} in image space.",
                        "recommended_action": "Review segmentation and confirm the parcel boundary in the field."
                    })
    return issues



def _irregularity_ratio(p: Parcel) -> float:
    """0 = perfectly matches its minimum bounding rectangle, 1 = highly irregular."""
    if not p.is_valid or p.polygon.area == 0:
        return 1.0
    mrr_area = p.polygon.minimum_rotated_rectangle.area
    if mrr_area == 0:
        return 1.0
    return round(max(0.0, 1.0 - (p.polygon.area / mrr_area)), 3)


def _elevation_for(parcel_id: str):
    cfg = ELEVATION_DEMO_CONFIG[parcel_id]
    dsm, dtm = synth_raster_pair(cfg["seed"], cfg["ground_m"], cfg["height_m"], overhang_px=cfg["overhang_px"])
    return analyze_parcel_elevation(parcel_id, dsm, dtm, overhang_offset_m=cfg["overhang_offset_m"])


def _confidence_for(parcel_id: str, issues_by_parcel: dict):
    """Authoritative risk/confidence evaluation for seeded parcels."""
    p = PARCELS[parcel_id]
    return _confidence_for_geometry(parcel_id, p, issues_by_parcel)


def _issues_by_parcel(issues):
    out: dict[str, list] = {}
    for i in issues:
        for pid in i.parcel_ids:
            out.setdefault(pid, []).append(i)
    return out


def _confidence_for_geometry(pseudo_id: str, polygon_parcel: Parcel, issues_by_parcel: dict):
    """Single authoritative risk/confidence calculation used by every API path.

    Topology, geometric irregularity, elevation disagreement and historical
    mismatch all enter the same weighted model. Elevation is computed from
    the configured deterministic demo surface for seeded parcels and from a
    deterministic prototype surface for EXT-* records. Historical comparison
    is only available for seeded demo parcels, so missing historical evidence
    contributes 0 rather than being invented.
    """
    pissues = issues_by_parcel.get(pseudo_id, [])
    has_overlap = any(i.issue_type == "overlap" for i in pissues)
    has_gap = any(i.issue_type == "gap" and i.status == "open" for i in pissues)
    has_invalid = any(i.issue_type in ("invalid_geometry", "self_intersection") for i in pissues)

    elev = _target_elevation(pseudo_id)
    ndsm_dis = abs(float(elev.overhang_offset_m)) if elev is not None else 0.0
    hist_shift = float(HISTORICAL_SHIFT_DEMO_M.get(pseudo_id, 0.0))

    conf = compute_confidence(
        pseudo_id, has_overlap=has_overlap, has_gap=has_gap, has_invalid_geometry=has_invalid,
        irregularity_ratio=_irregularity_ratio(polygon_parcel), ndsm_disagreement_m=ndsm_dis,
        historical_shift_m=hist_shift,
    )
    return conf


