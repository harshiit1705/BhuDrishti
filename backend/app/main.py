@app.get("/api/topology/issues")
def list_topology_issues(parcel_id: str | None = Query(None)):
    """Recalculate topology from the current authoritative geometry.

    Seeded BD-* parcels are evaluated together because their local-demo
    spatial relationships are meaningful within the fixture. EXT-* uploads
    are evaluated individually because their pixel-derived local coordinates
    are not georeferenced and therefore must not be compared with seeded or
    unrelated uploads. If parcel_id is supplied, only that record's issues
    are returned.
    """
    seeded = _authoritative_parcels()
    issues = run_topology_validation(seeded)
    ext_ids = {r.extraction_id for r in extraction_store.all()}
    for rec in extraction_store.all():
        vr = store.get(rec.extraction_id)
        geom = vr.verified_geometry if vr and vr.verified_geometry is not None else rec.geometry
        source = "surveyor_verified" if vr and vr.verified_geometry is not None else "ai_extraction"
        issues.extend(run_topology_validation([Parcel(rec.extraction_id, geom, source=source)]))
    if parcel_id:
        if parcel_id in PARCELS:
            issues = [i for i in issues if parcel_id in i.parcel_ids]
        elif parcel_id in ext_ids:
            issues = [i for i in issues if parcel_id in i.parcel_ids]
        else:
            raise HTTPException(404, "Parcel or extraction not found")
    return {
        "issues": [i.to_dict() for i in issues],
        "count": len(issues),
        "coordinate_system": _coordinate_system(),
        "is_demo_data": not any(pid.startswith("EXT-") for i in issues for pid in i.parcel_ids),
        "scope": parcel_id or "all",
    }


