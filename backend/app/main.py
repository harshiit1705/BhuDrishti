def _authoritative_parcel(parcel_id: str) -> Parcel:
    """Resolve the geometry that downstream GIS/risk/export views should use."""
    base = PARCELS[parcel_id]
    rec = store.get(parcel_id)
    if rec and rec.verified_geometry is not None:
        return Parcel(parcel_id=base.parcel_id, polygon=rec.verified_geometry,
                      source="surveyor_verified", owner=base.owner, ward=base.ward, land_use=base.land_use)
    return base


def _authoritative_parcels() -> list[Parcel]:
    return [_authoritative_parcel(pid) for pid in PARCELS]


