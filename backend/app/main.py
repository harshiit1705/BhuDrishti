# 3c. AI FEATURE EXTRACTION -- REAL, EXECUTABLE IMAGE INFERENCE
# ---------------------------------------------------------------------------
# This is a genuine prototype computer-vision pipeline (see
# extraction_engine.py docstring): PIL decode -> grayscale -> Otsu threshold
# -> morphological cleanup -> OpenCV contour detection -> polygon
# simplification. It is NOT a trained neural model and reports no
# accuracy/mIoU numbers. Geometry is generated fresh from the uploaded
# image's actual pixels -- it is never selected from the PARCELS fixture
# dict, and it is stored in the separate `extraction_store`, not in PARCELS.
@app.post("/api/extraction/infer")
async def infer_extraction(image: UploadFile = File(...)):
    raw = await image.read()
    try:
        img = extraction_engine.decode_image(raw, image.filename or "upload")
        result = extraction_engine.run_cv_inference(img)
    except extraction_engine.ImageDecodeError as e:
        raise HTTPException(400, f"Image decode error: {e}")
    except extraction_engine.InferenceError as e:
        raise HTTPException(422, f"Inference could not produce a usable geometry: {e}")

    record = extraction_store.save(ExtractionRecord(
        extraction_id=extraction_store.new_id(),
        source_filename=image.filename or "upload",
        geometry=result.geometry,
        image_width=result.image_width,
        image_height=result.image_height,
        image_format=result.image_format,
        confidence_heuristic=result.confidence_heuristic,
        pixel_polygon=result.pixel_polygon,
        inference_mode=result.inference_mode,
        notes=result.notes,
        is_demo_data=False,
    ))

    # Uploaded prototype images have no georeferencing. Their pixel-derived
    # geometry is therefore NOT in the same spatial reference as the seeded
    # cadastral fixture. Validate the extraction itself (including real GEOS
    # validity) but do not compare it with unrelated parcels or other uploads.
    # This prevents false EXT-vs-EXT / EXT-vs-BD overlap caused only by the
    # shared demo local anchor used by the CV prototype.
    temp_parcel = Parcel(parcel_id=record.extraction_id, polygon=record.geometry,
                          source="ai_extraction", owner=None, ward=None, land_use=None)
    issues = run_topology_validation([temp_parcel])
    by_parcel = _issues_by_parcel(issues)
    conf = _confidence_for_geometry(record.extraction_id, temp_parcel, by_parcel)
    own_issues = by_parcel.get(record.extraction_id, [])

    return {
        **record.to_dict(),
        "confidence": conf.to_dict(),
        "topology_issues": [i.to_dict() for i in own_issues],
        "topology_issue_count": len(own_issues),
        "priority": conf.priority,
        "compared_against": [],
        "elevation": None,
        "elevation_note": "No DSM/DTM exists for ad-hoc image uploads in this prototype; "
                           "elevation analysis is only available for the seeded demo parcel set.",
    }


